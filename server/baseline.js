// Strokes-to-hole-out baseline tables.
// All distances stored in yards. Putts are converted feet→yards before lookup.
//
// Scratch baseline: PGA Tour averages from Mark Broadie, "Every Shot Counts"
//   (ShotLink data). Tee / fairway / rough / sand / recovery from 10–600 yds,
//   putting from 1–90 ft. Recovery values under 100 yds are not in Broadie's
//   published table and are approximated.
// Hdcp15 baseline: approximate values for a ~15-handicap golfer. There is no
//   separate tee curve for this profile, so tee shots use the fairway curve.
//
// Outside a curve's range the nearest endpoint value is used.

function interpolate(curve, x) {
  if (x <= curve[0][0]) return curve[0][1];
  if (x >= curve[curve.length - 1][0]) return curve[curve.length - 1][1];
  for (let i = 0; i < curve.length - 1; i++) {
    const [x0, y0] = curve[i];
    const [x1, y1] = curve[i + 1];
    if (x >= x0 && x <= x1) {
      const t = (x - x0) / (x1 - x0);
      return y0 + t * (y1 - y0);
    }
  }
  return curve[curve.length - 1][1];
}

